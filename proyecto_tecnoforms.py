import numpy as np
import matplotlib.pyplot as plt
import tensorflow as tf

from sklearn.datasets import fetch_openml
from sklearn.model_selection import train_test_split, cross_val_score
from sklearn.neighbors import KNeighborsClassifier
from sklearn.svm import SVC
from sklearn.metrics import accuracy_score, classification_report



mnist= fetch_openml('mnist_784', version=1, as_frame= False)
x= mnist.data.astype('float32')
y= mnist.target.astype('int32')

print(x.shape)
print(y.shape)
print(x[0].shape)

plt.figure(figsize=(10,5))
for i in range(8):
  plt.subplot(2,4,i+1)
  plt.imshow(x[i].reshape(28,28))
  plt.title('Dígito: ' + str(y[i]))

print(y[:16])

"""## Actividad 2. Preparar las imágenes para los modelos"""

x=x/255 #NORMALIZAMOS LAS IMÁGENES
x=x.reshape(-1,28,28,1)

print('nueva forma de x: ', x.shape)
print('nueva forma de x: ', x[0].shape)

x_train, x_test, y_train, y_test= train_test_split(x,y,test_size=0.2, random_state=42)
x_train, x_val, y_train, y_val= train_test_split(x_train,y_train,test_size=0.1, random_state=42)

print('entrenamiento:', x_train.shape)
print('validación:', x_val.shape)
print('prueba:', x_test.shape)

#KNN y SVM trabajan con las imágenes aplanadas (vectores de 784 valores)
x_train_sub= x_train.reshape(-1,784)[:10000] #10 000 imágenes de entrenamiento para KNN y SVM
y_train_sub= y_train[:10000]
x_val_flat= x_val.reshape(-1,784)
x_test_flat= x_test.reshape(-1,784)

print(x_train_sub.shape)
print(x_val_flat.shape)
print(x_test_flat.shape)

"""## Actividad 3. Entrenar el modelo K-Vecinos Cercanos (KNN)"""

model_knn= KNeighborsClassifier(n_neighbors=3)
model_knn.fit(x_train_sub, y_train_sub)

y_pred_val= model_knn.predict(x_val_flat)
print('KNN Accuracy:', accuracy_score(y_val, y_pred_val))

"""## Actividad 4. Entrenar el modelo Support Vector Machine (SVM)"""

model_svm= SVC(kernel='rbf')
model_svm.fit(x_train_sub, y_train_sub)

y_pred_val= model_svm.predict(x_val_flat)
print('SVM accuracy:', accuracy_score(y_val, y_pred_val))

"""## Actividad 5. Entrenar la Red Neuronal Convolucional (CNN)"""

#RNA CONVOLUCIONAL
model= tf.keras.models.Sequential([
    tf.keras.layers.Input(shape=(28,28,1)), #OJO: Las imágenes ya NO están aplanadas
    tf.keras.layers.Conv2D(16, 3, activation='relu'),
    tf.keras.layers.MaxPooling2D(), #reducimos la dimensionalidad del mapa de caraterísticas
    tf.keras.layers.Conv2D(32, 3, activation='relu'),
    tf.keras.layers.MaxPooling2D(),
    tf.keras.layers.Conv2D(64, 3, activation='relu'),
    tf.keras.layers.MaxPooling2D(),
    tf.keras.layers.Flatten(), #aplanamos nuevamente la imagen para procesarla en capas densas

    #LA PREDICCIÓN FINAL LA TOMAN LAS CAPAS DENSAS
    tf.keras.layers.Dense(128, activation='relu'),
    tf.keras.layers.Dense(64, activation='relu'),
    tf.keras.layers.Dense(36, activation='relu'),
    tf.keras.layers.Dense(16, activation='relu'),
    tf.keras.layers.Dense(10, activation='softmax')
])
model.compile(optimizer='adam', loss='sparse_categorical_crossentropy', metrics=['accuracy'])

model.fit(x_train, y_train, epochs=10, validation_data=(x_val, y_val)) #evaluación con el conjunto de validación

y_pred_cnn= model.predict(x_test)
print(y_pred_cnn.argmax(1)[:16])
print(y_test[:16])

plt.figure(figsize=(10,5))
for i in range(8):
  plt.subplot(2,4,i+1)
  plt.imshow(x_test[i].reshape(28,28))
  plt.title(str(y_test[i])+' '+ str(y_pred_cnn.argmax(1)[i]))

"""## Actividad 6. Entrenamiento, validación y ajuste de modelos"""

#KNN: probamos distintos valores de k
for k in [3, 5, 7]:
  knn= KNeighborsClassifier(n_neighbors=k)
  knn.fit(x_train_sub, y_train_sub)
  print('KNN k =', k, '- accuracy en validación:', accuracy_score(y_val, knn.predict(x_val_flat)))

#SVM: probamos distintos kernels
for kernel in ['linear', 'rbf']:
  svm= SVC(kernel=kernel)
  svm.fit(x_train_sub, y_train_sub)
  print('SVM kernel =', kernel, '- accuracy en validación:', accuracy_score(y_val, svm.predict(x_val_flat)))

#SVM: probamos distintos valores de C (kernel rbf)
for c in [10, 100]:
  svm= SVC(kernel='rbf', C=c)
  svm.fit(x_train_sub, y_train_sub)
  print('SVM rbf C =', c, '- accuracy en validación:', accuracy_score(y_val, svm.predict(x_val_flat)))

"""## 7. Evaluación y comparación de resultados"""

print('Accuracy KNN:', accuracy_score(y_test, y_pred_knn))
print('Accuracy SVM:', accuracy_score(y_test, y_pred_svm))
print('Accuracy CNN:', accuracy_score(y_test, y_pred_cnn.argmax(1)))

print('KNN')
print(classification_report(y_test, y_pred_knn))

print('SVM')
print(classification_report(y_test, y_pred_svm))

print('CNN')
print(classification_report(y_test, y_pred_cnn.argmax(1)))

"""## El modelo más optimo es **Red Neuronal Convolucional (CNN)**"""

